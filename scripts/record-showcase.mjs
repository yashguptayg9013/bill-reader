// Records real Claude output on the sample bills for the static demo in docs/.
//
//   npm run dev                (in another terminal, with ANTHROPIC_API_KEY set)
//   npm run showcase:record
//
// Writes docs/showcase-data.js, which docs/index.html replays. Each run makes
// one API call per sample bill. `--expected` writes the known correct values
// instead (no API calls), clearly marked as not recorded.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const BASE = process.env.BASE_URL ?? "http://localhost:3000";
const OUT = path.join(here, "..", "docs", "showcase-data.js");
const SAMPLES = [
  { id: "intra-state", file: "intra-state-invoice.png", type: "image/png" },
  { id: "inter-state", file: "inter-state-invoice.png", type: "image/png" },
  { id: "phone-photo", file: "phone-photo-bill.jpg", type: "image/jpeg" },
];

function fromExpected(e) {
  return {
    supplier: { name: e.supplier_name, gstin: e.supplier_gstin },
    invoice_number: e.invoice_number,
    invoice_date: e.invoice_date,
    line_items: e.line_items.map((i) => ({ ...i, unit: null, discount: null, amount: i.taxable_value })),
    totals: {
      taxable_value: e.taxable_value, cgst: e.cgst, sgst: e.sgst, igst: e.igst,
      cess: null, other_charges: null, round_off: e.round_off, grand_total: e.grand_total,
    },
  };
}

const expectedOnly = process.argv.includes("--expected");
const data = { recorded: !expectedOnly, model: null, recordedAt: new Date().toISOString().slice(0, 10), samples: {} };

for (const s of SAMPLES) {
  if (expectedOnly) {
    const e = JSON.parse(await fs.readFile(path.join(here, "expected", s.file.replace(/\.\w+$/, ".json")), "utf8"));
    data.samples[s.id] = { seconds: null, bill: fromExpected(e) };
    continue;
  }
  const form = new FormData();
  const bytes = await fs.readFile(path.join(here, "..", "public", "samples", s.file));
  form.append("file", new Blob([bytes], { type: s.type }), s.file);
  const res = await fetch(`${BASE}/api/extract`, { method: "POST", body: form });
  const body = await res.json();
  if (!body.ok) {
    console.error(`✗ ${s.id}: ${body.error}`);
    process.exit(1);
  }
  data.model = body.model;
  data.samples[s.id] = { seconds: body.seconds, bill: body.bill };
  console.log(`✓ ${s.id}: ${body.bill.line_items.length} items in ${body.seconds}s`);
}

await fs.writeFile(
  OUT,
  `// Generated by scripts/record-showcase.mjs. Do not edit by hand.\nwindow.BILL_READER_SHOWCASE = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`wrote ${path.relative(process.cwd(), OUT)}${expectedOnly ? " (expected values, not recorded)" : ""}`);
